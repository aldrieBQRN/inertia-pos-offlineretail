<?php

/**
 * End-to-End Compatibility Test between:
 * 1. Portal License Generator (C:\laragon\www\inertia-pos-license-portal)
 * 2. POS License Validator & Activation (C:\laragon\www\inertia-pos-RETAIL-offline)
 */

echo "=== Inertia POS License Portal Compatibility Test ===\n\n";

// 1. Test Portal Generator Service via isolated process
$genScript = __DIR__ . '/run-portal-generate.php';
$genCmd = 'php ' . escapeshellarg($genScript) . ' "Corner Retail Store" "POS-AAD3-0752-1729-737A"';

echo "--- Step 1: Generating License via Standalone Portal Generator ---\n";
$output = shell_exec($genCmd);
$generated = json_decode(trim($output), true);

if (!is_array($generated) || empty($generated['license_key'])) {
    echo "  [FAIL] Malformed or empty output from portal: $output\n";
    exit(1);
}

echo "  [INFO] Generated License ID : " . $generated['license_id'] . "\n";
echo "  [INFO] Target Machine ID    : " . $generated['machine_id'] . "\n";
echo "  [INFO] Client Name          : " . $generated['client_name'] . "\n";
echo "  [INFO] License Key Token    : " . substr($generated['license_key'], 0, 30) . "... (" . strlen($generated['license_key']) . " chars)\n";
echo "  [PASS] Portal successfully generated signed license token.\n";

// 2. Test POS Validation using POS LicenseService
echo "\n--- Step 2: Validating Generated Token in POS Application ---\n";
require_once __DIR__ . '/../vendor/autoload.php';
$posApp = require __DIR__ . '/../bootstrap/app.php';
$posApp->make(\Illuminate\Contracts\Console\Kernel::class)->bootstrap();

$posLicenseService = $posApp->make(\App\Services\LicenseService::class);

$testMachineId = $generated['machine_id'];
$validation = $posLicenseService->validateToken($generated['license_key'], $testMachineId);

if (!$validation['valid']) {
    echo "  [FAIL] POS rejected license generated by portal: " . ($validation['error'] ?? 'Unknown error') . "\n";
    exit(1);
}
echo "  [PASS] POS accepted signature and payload: Valid Ed25519 signature verified!\n";

$payload = $validation['payload'];
if ($payload['product'] !== 'inertia-pos') {
    echo "  [FAIL] Unexpected product in payload: " . $payload['product'] . "\n";
    exit(1);
}
if ($payload['license_type'] !== 'perpetual') {
    echo "  [FAIL] Expected perpetual license type, got: " . $payload['license_type'] . "\n";
    exit(1);
}
if (!empty($payload['expires_at'])) {
    echo "  [FAIL] Lifetime license should not have expires_at, got: " . $payload['expires_at'] . "\n";
    exit(1);
}
echo "  [PASS] Payload confirmed: product=inertia-pos, type=perpetual, expires_at=null (Lifetime).\n";

// 3. Test Wrong Machine ID Rejection
echo "\n--- Step 3: Testing Wrong Machine Rejection ---\n";
$wrongValidation = $posLicenseService->validateToken($generated['license_key'], 'POS-9999-8888-7777-6666');
if (!$wrongValidation['valid'] && strpos($wrongValidation['error'], 'belong to this machine') !== false) {
    echo "  [PASS] Wrong machine correctly rejected: " . $wrongValidation['error'] . "\n";
} else {
    echo "  [FAIL] Wrong machine was NOT rejected properly!\n";
    exit(1);
}

// 4. Test Tampered License Rejection
echo "\n--- Step 4: Testing Tampered Token Rejection ---\n";
$tamperedToken = substr($generated['license_key'], 0, -6) . 'XXXXXX';
$tamperedValidation = $posLicenseService->validateToken($tamperedToken, $testMachineId);
if (!$tamperedValidation['valid'] && strpos($tamperedValidation['error'], 'signature') !== false) {
    echo "  [PASS] Tampered token correctly rejected: " . $tamperedValidation['error'] . "\n";
} else {
    echo "  [FAIL] Tampered token was NOT rejected properly!\n";
    exit(1);
}

// 5. Test Full POS Activation & Persistence in SQLite
echo "\n--- Step 5: Testing POS Activation & Database Persistence ---\n";
try {
    $activatedLicense = $posLicenseService->activate($generated['license_key']);
    echo "  [PASS] POS License activated: ID=" . $activatedLicense->license_id . ", Active=" . ($activatedLicense->is_active ? 'YES' : 'NO') . "\n";

    // Verify persistence
    $reloaded = \App\Models\License::where('machine_id', $testMachineId)->where('is_active', true)->first();
    if ($reloaded && $reloaded->license_id === $generated['license_id']) {
        echo "  [PASS] Activation persisted in SQLite database successfully.\n";
    } else {
        echo "  [FAIL] License was not persisted in SQLite.\n";
        exit(1);
    }
} catch (\Throwable $e) {
    echo "  [FAIL] Activation threw exception: " . $e->getMessage() . "\n";
    exit(1);
}

echo "\n==========================================================\n";
echo " ALL PORTAL COMPATIBILITY TESTS PASSED (100% SUCCESS)!\n";
echo "==========================================================\n";
